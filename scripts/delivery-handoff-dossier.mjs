export function deliveryHandoffDossier({
  completionAudit = {},
  agenticAudit = {},
  overview = {},
  t3Package = {},
  t3Evidence = {},
  modelContracts = {},
  generatedAt = new Date().toISOString()
} = {}) {
  const openCertificationGaps = overview.openCertificationGaps || completionAudit.openCertificationGaps || [];
  const agenticChecks = agenticAudit.completionMatrix || [];
  const agenticProvedCheckCount = agenticChecks.filter((item) => item.status === "proved").length;
  const localEvidencePassed = Boolean(completionAudit.localEvidencePassed && overview.localEvidencePassed);
  const finalGoalComplete = false;
  const status = localEvidencePassed ? "handoff-ready-with-open-certification-gaps" : "needs-local-evidence";

  return {
    status,
    generatedAt,
    finalGoalComplete,
    localEvidencePassed,
    verdict: completionAudit.verdict || "UNKNOWN",
    localRequirementCount: Number(completionAudit.localRequirementCount || 0),
    trackedNonLocalRequirementCount: Number(completionAudit.trackedNonLocalRequirementCount || 0),
    provedLocalRequirementCount: provedLocalRequirementCount(completionAudit),
    openCertificationGapCount: openCertificationGaps.length,
    openCertificationGaps,
    modelRouting: {
      primaryModel: modelContracts.coding?.primaryModel || "claude-sonnet-4-6",
      fallbackModel: modelContracts.coding?.fallbackModel || "gpt-5.3-codex-spark",
      fallbackAfterMs: modelContracts.coding?.fallbackAfterMs || 1000,
      imageModel: modelContracts.image?.model || "gpt-image-2"
    },
    agenticQa: {
      verdict: agenticAudit.verdict || "UNKNOWN",
      provedCheckCount: agenticProvedCheckCount,
      openIssueCount: (agenticAudit.issueList || []).filter((item) => item.status === "open").length,
      clickQaExit: agenticAudit.clickQaExit ?? null
    },
    t3Package: {
      status: t3Package.status || "missing",
      executionAllowed: t3Package.executionAllowed === true,
      laneCount: t3Package.packageSummary?.laneCount || 0,
      blockedLaneCount: t3Package.packageSummary?.blockedLaneCount || 0
    },
    t3Evidence: {
      status: t3Evidence.status || "missing",
      candidateCount: t3Evidence.candidateCount || 0,
      acceptedCandidateCount: t3Evidence.acceptedCandidateCount || 0,
      certificationStateChanged: t3Evidence.certificationStateChanged === true
    },
    sections: SECTIONS,
    artifactManifest: ARTIFACT_MANIFEST,
    artifactCount: ARTIFACT_MANIFEST.length,
    nextActions: openCertificationGaps.map((gap) => ({
      id: gap.id,
      riskTier: gap.riskTier || "T3",
      approvalRequired: true,
      action: gap.nextAction || gap.fix || "Run one explicitly approved T3 certification lane with rollback and evidence review."
    })),
    guardrails: {
      secretValuesReturned: false,
      externalCalls: false,
      managedDatabaseConnections: false,
      deployments: false,
      billingActions: false,
      finalCompletionClaimed: false
    }
  };
}

function provedLocalRequirementCount(completionAudit) {
  if (typeof completionAudit.provedLocalRequirementCount === "number") {
    return completionAudit.provedLocalRequirementCount;
  }
  return (completionAudit.requirements || [])
    .filter((item) => item.localRequired !== false && item.status === "proved")
    .length;
}

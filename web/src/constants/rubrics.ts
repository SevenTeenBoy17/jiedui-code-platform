// 计算思维六维表现性评价量规（初中信息科技 · 结对编程智能体版）
// 依据：《义务教育信息科技课程标准（2022年版）》
// 证据来源：任务分析、设计稿、作品版本、测试结果、学生解释、迁移任务与教师确认。
// 运行/报错/求助/时长等行为次数只用于定位原件，不得直接换算能力水平。

export type RubricKey =
  | 'abstract'
  | 'decompose'
  | 'model'
  | 'algorithm'
  | 'verify'
  | 'transfer'

export interface RubricLevel {
  /** 1 起步 / 2 基础 / 3 熟练 / 4 迁移创新 */
  lv: 1 | 2 | 3 | 4
  /** 水平短标题，用于 CeramicTile 标签 */
  title: string
  /** 可观察行为描述，≤40 字 */
  desc: string
}

export interface Rubric {
  key: RubricKey
  label: string
  /** 4 个水平，按 lv 升序 */
  levels: RubricLevel[]
  /** 必须能打开原件的证据线索；任何单一行为次数都不能直接定级 */
  signals: string[]
  /** 学生停在水平 1–2 时的教师干预建议 */
  intervention: string
}

